export const projectById = new Map(projects.map((project) => [project.id, project]))
export const projectBySlug = new Map(projects.map((project) => [project.slug, project]))
export const projectAliases = new Map(projects.flatMap((project) => [project.id, project.slug, ...project.aliases].map((alias) => [alias, project.id])))

export const findProject = (query) => {
  const normalized = query?.trim().toLowerCase()
  if (!normalized) return null
  const exactId = projectAliases.get(normalized)
  if (exactId) return projectById.get(exactId)
  return projects.find((project) => [project.title, project.shortTitle, project.category, ...project.stack]
    .some((value) => value.toLowerCase().includes(normalized))) || null
}

